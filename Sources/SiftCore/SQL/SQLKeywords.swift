/// The words Sift draws as keywords: PostgreSQL 17's reserved words and the common non-reserved ones,
/// matched case-insensitively. A word outside the list is an identifier.
public enum SQLKeywords {
    public static let all: Set<String> = Set(words.split(whereSeparator: { $0 == " " || $0 == "\n" }).map(String.init))

    /// True when `word` (any case) is a keyword.
    public static func contains(_ word: String) -> Bool { all.contains(word.uppercased()) }

    /// True when the ASCII bytes spell a keyword in any case. Allocates only for a word that is short enough to be one.
    static func contains(bytes: Slice<UnsafeBufferPointer<UInt8>>) -> Bool {
        guard bytes.count <= longest else { return false }
        var upper: [UInt8] = []
        upper.reserveCapacity(bytes.count)
        for b in bytes { upper.append(b >= 0x61 && b <= 0x7A ? b - 32 : b) }
        return all.contains(String(decoding: upper, as: UTF8.self))
    }

